package com.example.scholarmatch.notification.model;

import java.time.LocalDateTime;

public class Notification {

    private Long notificationId;
    private String recipientType;       // STUDENT, INSTITUTION
    private Long studentId;
    private Long institutionId;
    private String notificationType;    // DEADLINE_ALERT, CERTIFICATE_EXPIRY, SCHOLARSHIP_APPROVED, SCHOLARSHIP_REJECTED, GENERAL
    private Long relatedScholarshipId;
    private String title;
    private String message;
    private boolean read;
    private boolean emailSent;
    private LocalDateTime createdAt;

    public Notification() {
    }

    public Long getNotificationId() {
        return notificationId;
    }

    public void setNotificationId(Long notificationId) {
        this.notificationId = notificationId;
    }

    public String getRecipientType() {
        return recipientType;
    }

    public void setRecipientType(String recipientType) {
        this.recipientType = recipientType;
    }

    public Long getStudentId() {
        return studentId;
    }

    public void setStudentId(Long studentId) {
        this.studentId = studentId;
    }

    public Long getInstitutionId() {
        return institutionId;
    }

    public void setInstitutionId(Long institutionId) {
        this.institutionId = institutionId;
    }

    public String getNotificationType() {
        return notificationType;
    }

    public void setNotificationType(String notificationType) {
        this.notificationType = notificationType;
    }

    public Long getRelatedScholarshipId() {
        return relatedScholarshipId;
    }

    public void setRelatedScholarshipId(Long relatedScholarshipId) {
        this.relatedScholarshipId = relatedScholarshipId;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getMessage() {
        return message;
    }

    public void setMessage(String message) {
        this.message = message;
    }

    public boolean isRead() {
        return read;
    }

    public void setRead(boolean read) {
        this.read = read;
    }

    public boolean isEmailSent() {
        return emailSent;
    }

    public void setEmailSent(boolean emailSent) {
        this.emailSent = emailSent;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }
}